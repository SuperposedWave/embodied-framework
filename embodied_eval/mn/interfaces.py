"""Neither factory nor lifecycle passes the opposite adapter/configuration."""
from typing import Protocol
from pathlib import Path
from ..contracts import Budgets, Metric, PublicTask
from .contracts import (CapabilitySpec, SpaceSpec, BoundProfile, Context, ModelInput,
                        Prediction, TaskSpec, Observation, Action, StepResult)


class ModelAdapter(Protocol):
    def begin_episode(self, context: Context, task: PublicTask, profile: BoundProfile,
                      space: SpaceSpec) -> None: ...
    def observe(self, model_input: ModelInput) -> None: ...
    def predict(self, context: Context) -> Prediction: ...
    def end_episode(self, context: Context) -> None: ...
    def close(self) -> None: ...
    def diagnostics(self) -> dict[str, object]: ...


class BenchmarkAdapter(Protocol):
    def describe(self) -> SpaceSpec: ...
    def enumerate_tasks(self, episodes: tuple) -> list[TaskSpec]: ...
    def reset(self, task: TaskSpec, context: Context) -> Observation: ...
    def advance(self, action: Action, context: Context, remaining: Budgets) -> StepResult: ...
    def score(self, context: Context) -> dict[str, Metric]: ...
    def close(self) -> None: ...
    def diagnostics(self) -> dict[str, object]: ...
