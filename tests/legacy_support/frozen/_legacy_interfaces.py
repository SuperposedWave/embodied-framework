"""Both adapters implement these contracts without importing XPolicyLab."""
from typing import Protocol
from tests.legacy_support.frozen._legacy_contracts import ActionStep, AdaptationProfile, Budgets, CapabilitySpec, Context, DiscreteAction, Metric, ModelEndContext, ModelInput, NativeAction, Observation, Prediction, PublicTask, SpaceSpec, StepResult, TaskSpec, ToolCall


class ModelAdapter(Protocol):
    def describe(self) -> CapabilitySpec: ...
    def begin_episode(self, context: Context, task: PublicTask, space: SpaceSpec, profile: AdaptationProfile) -> None: ...
    def observe(self, model_input: ModelInput) -> None: ...
    def predict(self, request_context: Context) -> Prediction: ...
    def end_episode(self, context: ModelEndContext) -> None: ...
    def close(self) -> None: ...


class BenchmarkAdapter(Protocol):
    def describe(self) -> SpaceSpec: ...
    def enumerate_tasks(self, selection: dict[str, object]) -> list[TaskSpec]: ...
    def reset(self, task: TaskSpec, context: Context) -> Observation: ...
    def advance(self, control: ActionStep | NativeAction | DiscreteAction, request: Context, remaining_budget: Budgets) -> StepResult: ...
    def execute_tool(self, call: ToolCall, request: Context, remaining_budget: Budgets) -> StepResult: ...
    def score(self, context: Context) -> dict[str, Metric]: ...
    def close(self) -> None: ...
